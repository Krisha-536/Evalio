DROP TABLE IF EXISTS courses CASCADE;

-- -------------------------------------------------------------------------
-- 2. Table Definitions
-- -------------------------------------------------------------------------

-- 1. Courses
CREATE TABLE courses (
    course_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_name TEXT UNIQUE NOT NULL,
    description TEXT DEFAULT '',
    status TEXT DEFAULT 'Active',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. Administrators
CREATE TABLE administrators (
    admin_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    email TEXT UNIQUE NOT NULL,
    password TEXT NOT NULL,
    status TEXT DEFAULT 'Active',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. Students
CREATE TABLE students (
    student_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    enrollment_no TEXT UNIQUE NOT NULL,
    name TEXT NOT NULL,
    email TEXT UNIQUE NOT NULL,
    password TEXT NOT NULL,
    course_id BIGINT REFERENCES courses(course_id) ON DELETE SET NULL,
    phone TEXT DEFAULT '',
    status TEXT DEFAULT 'Active',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. Question Bank
CREATE TABLE questions (
    question_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id BIGINT REFERENCES courses(course_id) ON DELETE SET NULL,
    subject TEXT NOT NULL,
    topic TEXT NOT NULL,
    question_text TEXT NOT NULL,
    option_a TEXT NOT NULL,
    option_b TEXT NOT NULL,
    option_c TEXT NOT NULL,
    option_d TEXT NOT NULL,
    correct_option TEXT NOT NULL CHECK (correct_option IN ('A', 'B', 'C', 'D')),
    difficulty TEXT NOT NULL CHECK (difficulty IN ('Easy', 'Medium', 'Hard')),
    marks NUMERIC(5,2) DEFAULT 2.0,
    negative_marks NUMERIC(5,2) DEFAULT 0.5,
    status TEXT DEFAULT 'Active',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 5. Examinations
CREATE TABLE examinations (
    exam_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id BIGINT REFERENCES courses(course_id) ON DELETE SET NULL,
    exam_name TEXT NOT NULL,
    subject TEXT NOT NULL,
    description TEXT DEFAULT '',
    duration INTEGER NOT NULL, -- duration in minutes
    total_marks NUMERIC(6,2) DEFAULT 0,
    passing_marks NUMERIC(6,2) DEFAULT 0,
    negative_marking SMALLINT DEFAULT 0 CHECK (negative_marking IN (0, 1)),
    status TEXT DEFAULT 'Draft' CHECK (status IN ('Draft', 'Active', 'Completed', 'Archived')),
    shuffle_questions SMALLINT DEFAULT 1 CHECK (shuffle_questions IN (0, 1)),
    shuffle_options SMALLINT DEFAULT 1 CHECK (shuffle_options IN (0, 1)),
    result_published SMALLINT DEFAULT 0 CHECK (result_published IN (0, 1)),
    max_tab_switches INTEGER DEFAULT 3,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 6. Exam Questions Junction
CREATE TABLE exam_questions (
    exam_question_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exam_id BIGINT NOT NULL REFERENCES examinations(exam_id) ON DELETE CASCADE,
    question_id BIGINT NOT NULL REFERENCES questions(question_id) ON DELETE CASCADE,
    question_order INTEGER NOT NULL,
    UNIQUE(exam_id, question_id)
);

-- 7. Exam Schedules
CREATE TABLE schedules (
    schedule_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exam_id BIGINT UNIQUE NOT NULL REFERENCES examinations(exam_id) ON DELETE CASCADE,
    start_time TIMESTAMPTZ NOT NULL,
    end_time TIMESTAMPTZ NOT NULL,
    status TEXT DEFAULT 'Scheduled' CHECK (status IN ('Scheduled', 'In Progress', 'Completed', 'Cancelled'))
);

-- 8. Exam Attempts (Student test instances)
CREATE TABLE exam_attempts (
    attempt_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exam_id BIGINT NOT NULL REFERENCES examinations(exam_id) ON DELETE CASCADE,
    student_id BIGINT NOT NULL REFERENCES students(student_id) ON DELETE CASCADE,
    started_at TIMESTAMPTZ NOT NULL,
    submitted_at TIMESTAMPTZ,
    status TEXT DEFAULT 'In Progress' CHECK (status IN ('In Progress', 'Submitted', 'Auto-Submitted')),
    question_order JSONB NOT NULL, -- Array of question IDs in randomized order
    option_order JSONB NOT NULL,   -- Object of option shuffle mappings per question
    marked JSONB DEFAULT '[]'::jsonb, -- Array of bookmarked question IDs
    current_index INTEGER DEFAULT 0,
    tab_switches INTEGER DEFAULT 0,
    last_activity TIMESTAMPTZ NOT NULL,
    device_token TEXT,
    simulated SMALLINT DEFAULT 0,
    UNIQUE(exam_id, student_id)
);

-- 9. Saved Answers
CREATE TABLE answers (
    answer_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exam_id BIGINT NOT NULL REFERENCES examinations(exam_id) ON DELETE CASCADE,
    student_id BIGINT NOT NULL REFERENCES students(student_id) ON DELETE CASCADE,
    question_id BIGINT NOT NULL REFERENCES questions(question_id) ON DELETE CASCADE,
    selected_option TEXT CHECK (selected_option IS NULL OR selected_option IN ('A', 'B', 'C', 'D')),
    is_correct SMALLINT CHECK (is_correct IS NULL OR is_correct IN (0, 1)),
    marks_obtained NUMERIC(5,2) DEFAULT 0,
    saved_at TIMESTAMPTZ NOT NULL,
    UNIQUE(exam_id, student_id, question_id)
);

-- 10. Exam Results
CREATE TABLE results (
    result_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exam_id BIGINT NOT NULL REFERENCES examinations(exam_id) ON DELETE CASCADE,
    student_id BIGINT NOT NULL REFERENCES students(student_id) ON DELETE CASCADE,
    total_questions INTEGER NOT NULL,
    attempted_questions INTEGER NOT NULL,
    correct_answers INTEGER NOT NULL,
    wrong_answers INTEGER NOT NULL,
    score NUMERIC(6,2) NOT NULL,
    percentage NUMERIC(5,2) NOT NULL,
    result_status TEXT NOT NULL CHECK (result_status IN ('Pass', 'Fail')),
    generated_at TIMESTAMPTZ NOT NULL,
    UNIQUE(exam_id, student_id)
);

-- 11. Security & Activity Audit Logs
CREATE TABLE activity_logs (
    log_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exam_id BIGINT,
    user_role TEXT NOT NULL,
    user_id BIGINT,
    user_name TEXT NOT NULL,
    action TEXT NOT NULL,
    details TEXT DEFAULT '',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 12. Broadcast Notifications
CREATE TABLE notifications (
    notification_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id BIGINT,
    title TEXT NOT NULL,
    message TEXT NOT NULL,
    type TEXT DEFAULT 'info',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 13. Single-Device Session Enforcement
CREATE TABLE active_sessions (
    session_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_key TEXT UNIQUE NOT NULL,
    device_token TEXT NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- -------------------------------------------------------------------------
-- 3. Indexes for High Performance
-- -------------------------------------------------------------------------
CREATE INDEX idx_students_course ON students(course_id);
CREATE INDEX idx_students_enrollment ON students(enrollment_no);
CREATE INDEX idx_students_email ON students(email);
CREATE INDEX idx_questions_course ON questions(course_id);
CREATE INDEX idx_questions_difficulty ON questions(difficulty);
CREATE INDEX idx_questions_subject_topic ON questions(subject, topic);
CREATE INDEX idx_examinations_course ON examinations(course_id);
CREATE INDEX idx_exam_questions_exam ON exam_questions(exam_id);
CREATE INDEX idx_exam_attempts_student ON exam_attempts(student_id);
CREATE INDEX idx_exam_attempts_exam ON exam_attempts(exam_id);
CREATE INDEX idx_answers_attempt ON answers(exam_id, student_id);
CREATE INDEX idx_results_exam ON results(exam_id);
CREATE INDEX idx_results_student ON results(student_id);
CREATE INDEX idx_activity_logs_created ON activity_logs(created_at DESC);
CREATE INDEX idx_notifications_course ON notifications(course_id);

-- -------------------------------------------------------------------------
-- 4. Supabase Row Level Security (RLS) Configuration
-- -------------------------------------------------------------------------
-- Enable RLS and grant public/authenticated read & write policies
-- so your frontend or backend API key can perform CRUD seamlessly.

DO $$
DECLARE
    t text;
BEGIN
    FOR t IN
        SELECT table_name
        FROM information_schema.tables
        WHERE table_schema = 'public'
          AND table_type = 'BASE TABLE'
    LOOP
        EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY;', t);
        EXECUTE format('DROP POLICY IF EXISTS "Public access policy" ON public.%I;', t);
        EXECUTE format('CREATE POLICY "Public access policy" ON public.%I FOR ALL USING (true) WITH CHECK (true);', t);
    END LOOP;
END $$;

